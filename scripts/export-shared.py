#!/usr/bin/env python3
"""Export the wording and data the on-device engine shares with the server.

    python3 scripts/export-shared.py          # writes tolle/app/web/core/local/shared.json
    python3 scripts/export-shared.py --check  # exits 1 if the file is out of date (used by the tests)

The phone and tablet apps can run Tolle by themselves ("on this device only"). They use a JavaScript
copy of the server's logic (web/core/local and web/features/*/local.js), but the *words* – the AI's
instructions, the study purposes and audiences, settings defaults, study sites and the Bible's books –
come from the server code through this file, so there is only one place to change them.
"""
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "tolle" / "app"
OUT = APP / "web" / "core" / "local" / "shared.json"


def build() -> dict:
    os.environ.setdefault("TOLLE_DATA_DIR", tempfile.mkdtemp(prefix="tolle-export-"))
    sys.path.insert(0, str(APP))
    from server import features
    from server.core import settings
    from server.core.ai import instructions
    from server.core.ai import prompts as core_prompts
    from server.core.ai.providers import ONDEVICE_MODELS, PROVIDERS
    from server.core.bible import BOOKS
    from server.core.config import VERSION

    loaded = features.load()            # registers every feature's instructions and default settings
    from server.features.builder import prompts as builder
    from server.features.calling import prompts as calling
    from server.features.chat import prompts as chat
    from server.features.insights import prompts as insights
    from server.features.research import prompts as research

    defaults = dict(settings.DEFAULTS)
    for f in loaded:
        defaults.update({k: v for k, v in (f.settings or {}).items() if k not in defaults})
    return {
        "_comment": "Generated by scripts/export-shared.py from the server code – do not edit by hand.",
        "version": VERSION,
        "features": [{"id": f.id, "name": f.name, "description": f.description, "essential": f.essential}
                     for f in loaded],
        "instructions": [{"key": i.key, "label": i.label, "help": i.help, "group": i.group, "default": i.default}
                         for i in instructions._REGISTRY.values()],
        "levels": settings.LEVELS,
        "defaults": defaults,
        "secret_keys": sorted(settings.SECRET_KEYS),
        "default_sources": settings.DEFAULT_SOURCES,
        "providers": PROVIDERS,
        "ondevice_models": ONDEVICE_MODELS,
        "books": [{"name": n, "slug": s, "chapters": c, "abbrs": a} for n, s, c, a in BOOKS],
        "text": {
            "transcribe": core_prompts.transcribe_image(),
            "calling_opening": calling.calling_opening(""),
            "calling_summary": calling.calling_summary(),
        },
        "purposes": research.PURPOSES,
        "audiences": builder.AUDIENCES,
        "insight_modes": insights.INSIGHT_MODES,
        "chat_starters": chat.STARTERS,
    }


def main() -> None:
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date – run: python3 scripts/export-shared.py")
            sys.exit(1)
        print("shared.json is up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
